#ifndef COLORS_H
#define COLORS_H

/* Color codes. Put one before your text to change its color */
#define RED     "\033[1;31m"     // errors
#define GREEN   "\033[1;32m"     // success / done
#define YELLOW  "\033[1;33m"     // warnings
#define BLUE    "\033[1;34m"     // titles
#define CYAN    "\033[1;36m"     // info / help menu
#define RESET   "\033[0m"        // go back to normal color

#endif